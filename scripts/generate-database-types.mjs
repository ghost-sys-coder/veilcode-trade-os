import { writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import process from "node:process";

import pg from "pg";
import { databaseTestConnection } from "./lib/database-test-safety.mjs";

let connectionString = process.env.TRADE_OS_DATABASE_URL;
let connectionOptions;
if (process.argv.includes("--local")) {
  const status = JSON.parse(execFileSync("supabase",["status","--output","json"],{
    cwd: fileURLToPath(new URL("..",import.meta.url)),encoding: "utf8",stdio: ["ignore","pipe","pipe"],timeout: 15_000,
  }));
  connectionOptions = databaseTestConnection(status.DB_URL);
  connectionString = connectionOptions.connectionString;
}

if (!connectionString) {
  throw new Error("TRADE_OS_DATABASE_URL is required.");
}

const client = new pg.Client({
  connectionString,
  // TLS remains enabled. This exception is limited to schema introspection
  // because the managed pooler chain is not trusted by the local Node store.
  ssl: { rejectUnauthorized: false },
  ...connectionOptions,
});

function scalarType(column) {
  if (column.data_type === "ARRAY") {
    const element = { ...column, data_type: "USER-DEFINED", udt_name: column.udt_name.slice(1) };
    return `Array<${scalarType(element)}>`;
  }

  if (column.data_type === "USER-DEFINED" && column.udt_schema === "public") {
    return `Database["public"]["Enums"]["${column.udt_name}"]`;
  }

  switch (column.data_type) {
    case "bigint":
    case "integer":
    case "smallint":
      return "number";
    case "boolean":
      return "boolean";
    case "json":
    case "jsonb":
      return "Json";
    case "numeric":
    case "decimal":
      return "string";
    default:
      return "string";
  }
}

function propertyLine(column, mode) {
  const optional =
    mode === "Update" ||
    (mode === "Insert" &&
      (column.is_nullable === "YES" || column.column_default !== null || column.is_identity === "YES"));
  const nullable = column.is_nullable === "YES" ? " | null" : "";
  return `          ${column.column_name}${optional ? "?" : ""}: ${scalarType(column)}${nullable}`;
}

function renderTable(tableName, columns) {
  const sections = ["Row", "Insert", "Update"].map((mode) => {
    const properties = columns.map((column) => propertyLine(column, mode)).join("\n");
    return `        ${mode}: {\n${properties}\n        }`;
  });

  return `      ${tableName}: {\n${sections.join("\n")}\n        Relationships: []\n      }`;
}

function renderEnums(enums) {
  const byName = new Map();

  for (const row of enums) {
    const values = byName.get(row.enum_name) ?? [];
    values.push(JSON.stringify(row.enum_value));
    byName.set(row.enum_name, values);
  }

  return [...byName.entries()]
    .map(([name, values]) => `      ${name}: ${values.join(" | ")}`)
    .join("\n");
}

try {
  await client.connect();
  const [columnsResult, enumsResult] = await Promise.all([
    client.query(`
      select
        table_schema,
        table_name,
        column_name,
        ordinal_position,
        is_nullable,
        column_default,
        is_identity,
        data_type,
        udt_schema,
        udt_name
      from information_schema.columns
      where table_schema = 'public'
      order by table_name, ordinal_position
    `),
    client.query(`
      select type.typname as enum_name, value.enumlabel as enum_value
      from pg_catalog.pg_type type
      join pg_catalog.pg_namespace namespace on namespace.oid = type.typnamespace
      join pg_catalog.pg_enum value on value.enumtypid = type.oid
      where namespace.nspname = 'public'
      order by type.typname, value.enumsortorder
    `),
  ]);

  const tables = new Map();
  for (const column of columnsResult.rows) {
    const columns = tables.get(column.table_name) ?? [];
    columns.push(column);
    tables.set(column.table_name, columns);
  }

  const renderedTables = [...tables.entries()]
    .map(([tableName, columns]) => renderTable(tableName, columns))
    .join("\n");
  const renderedEnums = renderEnums(enumsResult.rows);
  const generated = `// Generated by scripts/generate-database-types.mjs from the ${connectionOptions ? "local" : "live"} Supabase schema.\n// Do not hand-edit this file.\n\nexport type Json =\n  | string\n  | number\n  | boolean\n  | null\n  | { [key: string]: Json | undefined }\n  | Json[]\n\nexport type Database = {\n  public: {\n    Tables: {\n${renderedTables}\n    }\n    Views: Record<string, never>\n    Functions: Record<string, never>\n    Enums: {\n${renderedEnums}\n    }\n    CompositeTypes: Record<string, never>\n  }\n  private: {\n    Tables: Record<string, never>\n    Views: Record<string, never>\n    Functions: {\n      correct_trade_plan_value: {\n        Args: {\n          p_field_name: string\n          p_new_value: Json\n          p_reason: string\n          p_trade_id: string\n          p_trade_target_id?: string | null\n        }\n        Returns: Database["public"]["Tables"]["trade_plan_corrections"]["Row"]\n      }\n    }\n    Enums: Record<string, never>\n    CompositeTypes: Record<string, never>\n  }\n}\n`;

  const publicFunctions = `    Functions: {
      classify_account_adjustment: {
        Args: {
          p_adjustment_id: string
          p_is_performance_neutral: boolean
          p_reason: string
        }
        Returns: Database["public"]["Tables"]["account_adjustments"]["Row"]
      }
      complete_trade_rule_review: {
        Args: { p_results: Json; p_trade_id: string }
        Returns: Database["public"]["Tables"]["trade_rule_reviews"]["Row"]
      }
      correct_trade_plan_value: {
        Args: {
          p_field_name: string
          p_new_value: string
          p_reason: string
          p_trade_id: string
          p_trade_target_id?: string | null
        }
        Returns: Database["public"]["Tables"]["trade_plan_corrections"]["Row"]
      }
      replace_trade_targets: {
        Args: { p_targets: Json; p_trade_id: string }
        Returns: undefined
      }
      transition_account_status: {
        Args: {
          p_account_id: string
          p_new_status: Database["public"]["Enums"]["account_status"]
          p_effective_at: string
          p_failure_reason?: Database["public"]["Enums"]["account_failure_reason"] | null
          p_notes?: string | null
        }
        Returns: Database["public"]["Tables"]["account_status_events"]["Row"]
      }
      update_trade_target_execution: {
        Args: { p_targets: Json; p_trade_id: string }
        Returns: undefined
      }
    }`;
  const generatedWithFunctions = generated.replace(
    "    Functions: Record<string, never>",
    publicFunctions,
  );

  await writeFile(new URL("../types/database.ts", import.meta.url), generatedWithFunctions, "utf8");
  console.log(`Generated ${tables.size} public table definitions and complete public enums.`);
} finally {
  await client.end();
}
