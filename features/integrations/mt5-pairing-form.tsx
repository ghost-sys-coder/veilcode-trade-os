"use client";
import { useActionState, useRef, useState } from "react";
import { MutationForm } from "@/components/app/mutation-form";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Textarea } from "@/components/ui/textarea";
import { mt5PairingProposalSchema, type Mt5PairingProposal } from "@/domain/integrations/mt5-pairing";
import { approvePairingAction } from "./mt5-pairing-action";

export function Mt5PairingForm({profileId, version, clientId, accountId, operationId, available, existing}: {
  profileId: string; version: string; clientId: string; accountId: string; operationId: string; available: boolean;
  existing: {id: string; version: string; status: string} | null;
}) {
  const [proposal, setProposal] = useState<Mt5PairingProposal | null>(null);
  const [error, setError] = useState("");
  const readGeneration = useRef(0);
  const [state, action, pending] = useActionState(approvePairingAction, {message: "", ready: false});
  const matches = proposal !== null && proposal.profileId === profileId && proposal.clientId === clientId && proposal.accountId === accountId
    && (existing ? proposal.existingConnectionId === existing.id && existing.status === "PAUSED" : proposal.existingConnectionId === null);
  return <MutationForm action={action} className="space-y-4">
    <input type="hidden" name="profile_id" value={profileId} /><input type="hidden" name="profile_version" value={version} />
    <input type="hidden" name="operation_id" value={operationId} /><input type="hidden" name="connection_version" value={existing?.version ?? ""} />
    <input type="hidden" name="proposal" value={proposal ? JSON.stringify(proposal) : ""} />
    <div className="grid gap-2"><Label htmlFor="pairing-file">Companion terminal review file</Label>
      <Input id="pairing-file" type="file" accept=".json,application/json" disabled={!available || pending || state.ready}
        onChange={async event => {
          const generation = ++readGeneration.current;
          setProposal(null); setError("");
          try {
            const file = event.target.files?.[0];
            if (!file || file.size > 8192) throw Error();
            const value = mt5PairingProposalSchema.parse(JSON.parse(await file.text()));
            if (generation === readGeneration.current) setProposal(value);
          } catch { if (generation === readGeneration.current) setError("Select a valid public terminal review file generated by the companion. No credentials or manifest files are accepted."); }
        }} />
    </div>
    {proposal ? <div className="space-y-2 rounded-lg border border-border/70 bg-muted/30 p-4 text-sm">
      <p className="font-semibold">{proposal.terminal.identity.server} · {proposal.terminal.identity.login} · DEMO</p>
      <p>{proposal.terminal.identity.currencyCode} ({proposal.terminal.identity.currencyPrecision} decimals) · {proposal.terminal.identity.positionMode}</p>
      <p className="break-all text-xs text-muted-foreground">{proposal.terminal.executable}</p>
      <p className="break-all text-xs text-muted-foreground">Data folder: {proposal.terminal.dataPath}</p>
      <p className="text-xs text-muted-foreground">Observed {proposal.observedAt}. Approval requires a proposal less than 15 minutes old.</p>
      {!matches ? <p role="alert">This proposal does not match this setup or its existing paused connection.</p> : null}
    </div> : null}
    <p className="text-xs leading-5 text-muted-foreground">{existing
      ? "Adoption requires the companion to inspect your existing PAUSED manifest, unchanged broker identity and zero local pending uploads. Approval preserves imported history and fences the old worker; it does not revoke unrelated clients."
      : "This approves a new account mapping only. It does not approve history, symbol mappings, collection or automatic publication."}</p>
    <div className="grid gap-2"><Label htmlFor="pairing-reason">Mapping approval reason</Label>
      <Textarea id="pairing-reason" name="reason" required minLength={8} maxLength={1000} disabled={!available || pending || state.ready} /></div>
    <Label className="flex items-start gap-3 text-sm leading-6"><input className="mt-1 accent-primary" type="checkbox" name="confirmed" required disabled={!available || pending || !matches || state.ready} />
      I confirm this is my dedicated demo terminal and the displayed account is the intended Trade OS mapping.</Label>
    <Button type="submit" disabled={!available || pending || !matches || state.ready}>{pending ? "Approving mapping…" : existing ? "Approve paused same-terminal adoption" : "Approve terminal mapping"}</Button>
    {error ? <p role="alert" className="text-sm">{error}</p> : null}
    {state.message ? <p role={state.ready ? "status" : "alert"} className="text-sm leading-6">{state.message}</p> : null}
  </MutationForm>;
}
